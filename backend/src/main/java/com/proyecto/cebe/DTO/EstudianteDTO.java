package com.proyecto.cebe.DTO;

public class EstudianteDTO {
    private String nombreEstudiante;
    private String dniEstudiante;
    private String gradoSeccion;
    private String vacunas;
    private String enfermedades;
    private String lenguas;
    private String discapacidad;
    
    public String getNombreEstudiante() {
        return nombreEstudiante;
    }
    public void setNombreEstudiante(String nombreEstudiante) {
        this.nombreEstudiante = nombreEstudiante;
    }
    public String getDniEstudiante() {
        return dniEstudiante;
    }
    public void setDniEstudiante(String dniEstudiante) {
        this.dniEstudiante = dniEstudiante;
    }
    public String getGradoSeccion() {
        return gradoSeccion;
    }
    public void setGradoSeccion(String gradoSeccion) {
        this.gradoSeccion = gradoSeccion;
    }
    public String getVacunas() {
        return vacunas;
    }
    public void setVacunas(String vacunas) {
        this.vacunas = vacunas;
    }
    public String getEnfermedades() {
        return enfermedades;
    }
    public void setEnfermedades(String enfermedades) {
        this.enfermedades = enfermedades;
    }
    public String getLenguas() {
        return lenguas;
    }
    public void setLenguas(String lenguas) {
        this.lenguas = lenguas;
    }
    public String getDiscapacidad() {
        return discapacidad;
    }
    public void setDiscapacidad(String discapacidad) {
        this.discapacidad = discapacidad;
    }

}
